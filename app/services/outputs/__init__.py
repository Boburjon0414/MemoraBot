"""AI-generated learning artifact storage.

This package owns the `FeatureOutput` persistence layer — the single table
where every AI-generated artifact (quiz, flashcard set, summary, chat
session, presentation outline, Q&A session) is stored.

Public surface
--------------
  OutputType              — enum of all artifact types
  Payload models          — Pydantic models that validate payload_json per type:
      QuizPayload, FlashcardPayload, SummaryPayload,
      QASessionPayload, ChatSessionPayload, PresentationOutlinePayload
  FeatureOutputService    — domain service: save, load (typed), list, archive

Why one table instead of one table per feature
-----------------------------------------------
Each artifact type shares the same lifecycle: generated by AI, stored for
the user, optionally revisited or archived.  A generic `feature_outputs`
table with a `payload_json` column means:

  - Adding Flashcards = define FlashcardPayload + OutputType.FLASHCARD_SET.
    Zero schema migrations. Zero new repositories.
  - Listing "all my quizzes" = SELECT WHERE output_type = 'quiz'.
  - Archiving any artifact = UPDATE SET is_archived = TRUE.

The Pydantic payload models enforce schema at the service layer so
`payload_json` is never written or read as raw unvalidated JSON by callers.
"""
