"""Pydantic payload schemas for every `FeatureOutput` artifact type.

Each schema validates the `payload_json` column of a `FeatureOutput` row.
`FeatureOutputService.save()` serialises a schema instance to JSON before
writing; `FeatureOutputService.load()` deserialises and validates on read.

This two-way validation means:
  - No untyped JSON ever escapes the service layer.
  - Adding a new field to a schema is backward-compatible (existing rows
    deserialise fine — Pydantic ignores extra fields by default).
  - Removing a required field requires a migration or a `default` value.

Schema design principles
------------------------
  - Keep field names short and predictable — they are stored as-is in JSON.
  - Use plain Python types (str, int, float, list, dict) — no custom types
    that add serialisation complexity.
  - Every schema has a `version: int = 1` field so future schema evolution
    can be detected and handled by the service.

Current schemas (Step 7)
--------------------------
  QuizPayload            — a generated quiz with N questions
  FlashcardPayload       — a set of flashcards (front/back pairs)
  SummaryPayload         — an AI-generated text summary
  QASessionPayload       — a document Q&A session (question + answer)
  ChatSessionPayload     — an AI chat session (message history)
  PresentationOutlinePayload — a slide deck outline
"""

from __future__ import annotations

from pydantic import BaseModel, Field


# ── Quiz ───────────────────────────────────────────────────────────────── #

class QuizQuestion(BaseModel):
    """One question in a generated quiz.

    Field naming follows the AI output schema exactly.
    `correct_option` is the 0-based index of the correct answer — used
    directly as Telegram's `correct_option_id` in `send_poll()`.
    `correct_index` is kept as a backward-compatible alias.
    """

    question: str
    options: list[str]          # exactly 2–10 answer options
    correct_option: int = 0     # 0-based index — Telegram's correct_option_id
    explanation: str = ""       # shown after answering; injected into poll explanation
    source_chunk_id: int | None = None  # ContentChunk.id this Q was drawn from
    quiz_type: str = "meaning"  # "meaning" | "synonym" | "antonym" | "gap_fill" | "grammar"

    @property
    def correct_index(self) -> int:
        """Backward-compatible alias for correct_option."""
        return self.correct_option


class QuizPayload(BaseModel):
    """Payload for OutputType.QUIZ.

    Generated by QuizService from a user's vocabulary or a ContentSource.
    Stored as-is in feature_outputs.payload_json.

    `title` is the display name (from AI JSON output).
    `topic` is derived from title when not explicitly provided.
    `difficulty` defaults to empty string when not provided by AI.
    """

    version: int = 1
    title: str = ""                # AI output field — display name
    topic: str = ""                # derived or explicitly set
    difficulty: str = ""           # CEFR level; empty when not known
    questions: list[QuizQuestion]
    source_id: int | None = None   # ContentSource.id if from a document
    passage: str = ""              # Reading quiz passage — shown ONCE before questions start

    def model_post_init(self, __context: object) -> None:
        """Derive topic from title when topic is empty."""
        if not self.topic and self.title:
            object.__setattr__(self, "topic", self.title)

    @property
    def question_count(self) -> int:
        return len(self.questions)


# ── Flashcards ─────────────────────────────────────────────────────────── #

class Flashcard(BaseModel):
    """One flashcard (front / back pair)."""

    front: str                  # The prompt side (word, question, term)
    back: str                   # The answer side (definition, translation)
    hint: str | None = None     # Optional mnemonic hint
    source_chunk_id: int | None = None


class FlashcardPayload(BaseModel):
    """Payload for OutputType.FLASHCARD_SET."""

    version: int = 1
    topic: str
    cards: list[Flashcard]
    source_id: int | None = None

    @property
    def card_count(self) -> int:
        return len(self.cards)


# ── Summary ────────────────────────────────────────────────────────────── #

class SummaryPayload(BaseModel):
    """Payload for OutputType.SUMMARY.

    A concise AI-generated summary of a ContentSource or topic.
    """

    version: int = 1
    summary_text: str
    key_points: list[str] = Field(default_factory=list)
    word_count: int = 0
    source_id: int | None = None
    language: str = "en"        # language of the summary output


# ── Document Q&A ───────────────────────────────────────────────────────── #

class QATurn(BaseModel):
    """One question-answer exchange in a document Q&A session."""

    question: str
    answer: str
    source_chunk_ids: list[int] = Field(default_factory=list)
    # IDs of ContentChunk rows used as context for this answer.
    # Enables citation display ("Answer based on page 3").


class QASessionPayload(BaseModel):
    """Payload for OutputType.QA_SESSION.

    A session of one or more questions answered against a ContentSource.
    New QATurn items are appended as the session continues; the entire
    updated payload is re-serialised and stored.
    """

    version: int = 1
    source_id: int
    turns: list[QATurn] = Field(default_factory=list)

    @property
    def turn_count(self) -> int:
        return len(self.turns)


# ── AI Chat session ────────────────────────────────────────────────────── #

class ChatMessage(BaseModel):
    """One message in an AI chat session."""

    role: str           # "user" | "assistant" | "summary"
    content: str
    occurred_at: str    # ISO 8601 UTC string; str to avoid datetime JSON issues


class ChatSessionPayload(BaseModel):
    """Payload for OutputType.CHAT_SESSION.

    Stores the conversation history for one AI chat session.
    When the session exceeds the context budget, old messages are replaced
    by a single ChatMessage(role="summary", ...) before new ones are appended.
    """

    version: int = 1
    messages: list[ChatMessage] = Field(default_factory=list)
    context_summary: str | None = None
    # A running summary of the conversation so far, maintained by AIChatService
    # when the message count exceeds the summarisation threshold.

    @property
    def message_count(self) -> int:
        return len(self.messages)


# ── Presentation outline ───────────────────────────────────────────────── #

class PresentationSlide(BaseModel):
    """One slide in a presentation outline."""

    title: str
    bullets: list[str]
    speaker_notes: str | None = None
    source_chunk_id: int | None = None


class PresentationOutlinePayload(BaseModel):
    """Payload for OutputType.PRESENTATION_OUTLINE.

    A structured presentation outline generated from a topic or ContentSource.
    Can be exported to PPTX via python-pptx (future feature).
    """

    version: int = 1
    title: str
    slides: list[PresentationSlide]
    source_id: int | None = None

    @property
    def slide_count(self) -> int:
        return len(self.slides)
